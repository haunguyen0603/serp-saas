import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=path.resolve('.tools/m7l-final-release');
const dir=path.join(root,'docs/verification-artifacts/milestone-7l-deployment');
function json(file){const b=fs.readFileSync(file);return JSON.parse(b.toString(b[0]===255&&b[1]===254?'utf16le':'utf8').replace(/^\uFEFF/,''));}
const read=name=>json(path.join(dir,name));
const before=read('before-http.json');
const after=read('after-http.json');
const builds=new Set(after.results.map(r=>r.buildId).filter(Boolean));
assert.equal(builds.size,1);
const buildId=[...builds][0];
assert.notEqual(buildId,before.results[0].buildId);
const cloud=read('checks-success.json');
assert.equal(cloud.sha,'18d3a19862a504c052f38533237bc01162b62d57');
assert(cloud.checks.some(c=>c.name==='serp-web-main (serp-saas)'&&c.provider==='google-cloud-developer-connect'&&c.conclusion==='success'));
assert(cloud.checks.some(c=>c.name==='serp-backend-main (serp-saas)'&&c.conclusion==='neutral'));
const seo=read('seo/after.json');
const local=json(path.join(root,'docs/verification-artifacts/milestone-7l-final/linux-20261101/seo/after.json'));
assert.deepEqual(seo,local);
const browser=read('seo/browser-qa.json');
assert.equal(browser.results.length,88);
assert(browser.results.every(r=>r.errors.length===0&&!r.overflow));
assert.equal(browser.results.filter(r=>r.axe==='zero violations').length,44);
const http=read('m7d/http-smoke.json');
assert.equal(http.passed,23);
assert.deepEqual([http.accounts_created,http.rank_checks_created,http.payments_created,http.emails_sent],[0,0,0,0]);
const m7d=read('m7d/browser-smoke.json');
assert.equal(m7d.checks.length,3);
assert.deepEqual([m7d.page_errors,m7d.hydration_errors],[[],[]]);
assert(m7d.refresh_responses.every(r=>r.origin==='https://api.serpsaas.com'&&r.status===401));
const runtime=read('post-deploy-runtime-audit.json');
assert.equal(runtime.metadata.vulnerabilities.total,0);
const full=read('post-deploy-full-audit.json');
assert.deepEqual([full.metadata.vulnerabilities.high,full.metadata.vulnerabilities.critical],[0,0]);
const extra=read('production-extra-smoke.json');
assert.equal(extra.checks.length,6);
const result={result:'PASS',releaseSource:cloud.sha,buildId,previousBuildId:before.results[0].buildId,cloudBuildId:'d605560d-75e7-4c4b-a846-0bc93ab37a14',frontendDeployed:true,backendDeployed:false,publicUrls:seo.urls.length,seoIdenticalToVerifiedLinuxArtifact:true,seoBrowserCases:browser.results.length,axeRuns:44,browserVersion:browser.browserVersion,m7dHttpChecks:http.passed,m7dBrowserChecks:m7d.checks.length,extraHttpChecks:extra.checks.length,runtimeAudit:runtime.metadata.vulnerabilities,fullAudit:full.metadata.vulnerabilities,productionAccountsCreated:0,productionRankChecksCreated:0,productionPaymentsCreated:0,productionEmailsSent:0,checkedAt:new Date().toISOString()};
