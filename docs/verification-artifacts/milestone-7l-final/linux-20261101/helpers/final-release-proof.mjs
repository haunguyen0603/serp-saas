import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root = path.resolve('.tools/m7l-final-release');
const base = path.join(root, 'docs/verification-artifacts/milestone-7l-final/linux-20261101');
const readText = file => { const b = fs.readFileSync(file); return b.toString(b[0] === 255 && b[1] === 254 ? 'utf16le' : 'utf8').replace(/^\uFEFF/, ''); };
const json = name => JSON.parse(readText(path.join(base, name)));
const backend = json('backend-junit-summary.json');
assert.deepEqual([backend.tests, backend.failures, backend.errors, backend.skipped, backend.focusedM7D, backend.focusedFailures], [402, 0, 0, 0, 59, 0]);
assert(Object.values(json('frontend-gates.json')).every(code => code === 0));
assert(Object.values(json('backend-static-checks.json')).every(code => code === 0));
assert(json('migration-results.json').length === 7 && json('migration-results.json').every(step => step.exit === 0));
assert(readText(path.join(base, 'infrastructure-linux-final.txt')).includes('Ran 56 tests'));
assert(readText(path.join(base, 'infrastructure-linux-final.txt')).trim().endsWith('OK'));
const runtime = json('linux-runtime-audit.json');
const full = json('linux-full-audit.json');
assert.equal(runtime.metadata.vulnerabilities.total, 0);
assert.equal(full.metadata.vulnerabilities.high, 0);
assert.equal(full.metadata.vulnerabilities.critical, 0);
assert.equal(full.metadata.vulnerabilities.moderate, 16);
const lock = JSON.parse(fs.readFileSync(path.join(root, 'frontend/package-lock.json')));
for (const finding of Object.values(full.vulnerabilities)) for (const node of finding.nodes) assert.equal(lock.packages[node].dev, true, node);
const browser = json('browser-summary.json');
assert.deepEqual([browser.m7lCases, browser.m7lAxeRuns, browser.m7dChecks, browser.m7dScreenshots, browser.m7dAxeViolations, browser.m7dPageErrors, browser.m7dConsoleErrors], [88, 44, 13, 30, 0, 0, 0]);
assert(readText(path.join(base, 'app-browser.txt')).includes('44 cases, no page/hydration errors or admin requests'));
const frontend = json('frontend-production-artifact.json');
assert.equal(frontend.platform, 'linux');
assert.equal(frontend.next, '16.4.3');
assert(Object.values(frontend.absentDevelopmentPackages).every(Boolean));
assert(json('production-backend-health.json').every(r => r.status === 200 && r.body.status === 'ok'));
assert.equal(json('linux-image-optimization.json').status, 200);
assert.equal(json('seo/after.json').urls.length, 27);
const finalSeo = json('seo/after.json');
const priorSeo = JSON.parse(readText(path.join(root, 'docs/verification-artifacts/milestone-7l-integration/seo/after.json')));
let seoIdenticalToIntegration = true;
try { assert.deepEqual(finalSeo, priorSeo); } catch { seoIdenticalToIntegration = false; }
const cleanup = json('cleanup.json');
assert.equal(cleanup.remainingQaContainers.length, 0);
assert(cleanup.ports.every(p => !p.listening));
const report = fs.readFileSync('.tools/m7l-final-setup/final-report.md', 'utf8');
const missingLinks = [...report.matchAll(/\]\((verification-artifacts\/[^)]+)\)/g)].map(m => m[1]).filter(p => !fs.existsSync(path.join(root, 'docs', p)));
assert.deepEqual(missingLinks, []);
fs.writeFileSync(path.join(base, 'release-gates.json'), JSON.stringify({ mandatoryGates: 'PASS', recommendation: 'READY FOR PRODUCTION for the reviewed local snapshot; no deployment approval', backend, frontendTests: 342, frontendFiles: 37, infrastructureTests: 56, migrations: 'PASS', browser, publicUrls: 27, seoIdenticalToIntegration, runtimeAudit: runtime.metadata.vulnerabilities, fullAudit: full.metadata.vulnerabilities, remainingFindingsDevelopmentOnly: true, buildId: frontend.buildId, artifacts: json('validated-runtime-containers.json'), cleanupComplete: true, remote: json('git-end.json') }, null, 2));
console.log(JSON.stringify({ mandatoryGates: 'PASS', reportLinksValid: true, seoIdenticalToIntegration, remainingDevelopmentFindings: 16 }));
