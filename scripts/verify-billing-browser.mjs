import { verifyResponsive } from "./browser-responsive.mjs";
// M6A real browser journey, local fake-provider services only.
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { execFileSync } from "node:child_process";
import { pathToFileURL } from "node:url";
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_EXECUTABLE });
const base = process.env.FRONTEND_URL ?? "http://localhost:3000";
const api = process.env.API_URL ?? "http://localhost:8000";
const errors = [];
const password = "M6a browser verification password";
try {
  const customerContext = await browser.newContext();
  const page = await customerContext.newPage();
  page.on("pageerror", error => errors.push(error.message));
  const email = `m6a-browser-${randomUUID()}@example.com`;
  await page.goto(`${base}/signup`);
  await page.getByLabel("Email", { exact: true }).fill(email);
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByLabel("Confirm Password", { exact: true }).fill(password);
  await page.getByRole("checkbox").check();
  const signup = page.waitForResponse(r => r.url().endsWith("/auth/register"));
  await page.getByRole("button", { name: "Create Account" }).click();
  const account = await (await signup).json();
  await page.waitForURL(`${base}/app`);
  await page.getByRole("link", { name: "Billing & Usage" }).click();
  await page.getByText("Desktop Free", { exact: true }).waitFor();
  await page.getByText("Mobile Free", { exact: true }).waitFor();
  assert.equal(await page.getByRole("button", { name: "Activate Plan" }).count(), 0);
  await page.goto(`${base}/app/projects/new`);
  await page.getByLabel("Project name").fill("M6A browser project");
  await page.getByLabel("Country", { exact: true }).fill("vn");
  await page.getByLabel("Language", { exact: true }).fill("vi");
  await page.getByLabel("Keywords, one per line").fill("billing browser check");
  await page.getByRole("button", { name: "Create Project" }).click();
  await page.waitForURL(/\/app\/projects\/[0-9a-f-]+$/);
  const projectId = page.url().split("/").pop();
  await page.getByRole("button", { name: "Check Rankings" }).click();
  await page.getByText("Ranking checks queued.", { exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('progress[aria-label="Batch progress"]')?.value === 100);
  const headers = { Authorization: `Bearer ${account.access_token}` };
  const extra = await page.request.post(`${api}/api/v1/projects`, { headers, data: { name: "Limit", country_code: "VN", language_code: "vi", device: "desktop", keywords: ["extra"] } });
  assert.equal(extra.status(), 409);
  const keywordLimit = await page.request.post(`${api}/api/v1/projects/${projectId}/keywords/bulk`, { headers, data: { keywords: Array.from({length:50},(_,i)=>`limit ${i}`) } });
  assert.equal(keywordLimit.status(), 409);
  await page.goto(`${base}/settings/billing`);
  await page.getByRole("region", { name: "desktop", exact: true }).getByText("1 / 100", { exact: true }).waitFor();
  await page.getByRole("region", { name: "mobile", exact: true }).getByText("0 / 50", { exact: true }).waitFor();
  assert.equal((await page.request.get(`${api}/api/v1/admin/customers`, { headers })).status(),403);
  await page.goto(`${base}/admin/customers`);
  await page.getByText("Administrator access required").waitFor();

  const adminContext = await browser.newContext();
  const adminPage = await adminContext.newPage();
  adminPage.on("pageerror", error => errors.push(error.message));
  const adminEmail = `m6a-admin-browser-${randomUUID()}@example.com`;
  const created = await adminPage.request.post(`${api}/api/v1/auth/register`, { data: { email:adminEmail, password, accept_terms:true } });
  assert.equal(created.status(),201);
  // Explicit local operator bootstrap; no public role-elevation endpoint exists.
  execFileSync(process.env.DOCKER_BIN ?? "docker", ["compose","exec","-T","backend","python","-m","scripts.platform_admin",adminEmail], { env: process.env, stdio:"pipe" });
  await adminContext.clearCookies();
  await adminPage.goto(`${base}/login`);
  await adminPage.getByLabel("Email", { exact:true }).fill(adminEmail);
  await adminPage.getByLabel("Password", { exact:true }).fill(password);
  await adminPage.getByRole("button", { name:"Log in", exact:true }).click();
  await adminPage.waitForURL(`${base}/app`);
  await adminPage.getByRole("link", { name:"Customers", exact:true }).click();
  await adminPage.getByLabel("Search email").fill(email);
  await adminPage.getByRole("link", { name:email, exact:true }).click();
  await adminPage.getByText("Desktop Free", { exact:true }).first().waitFor();
  const end = new Date(Date.now()+90*86400000).toISOString().slice(0,16);
  async function activate(code, reference, replace=false) {
    await adminPage.getByRole("combobox", { name:/^Plan/ }).selectOption(code);
    await adminPage.getByLabel("Period end", { exact:true }).fill(end);
    if (await adminPage.getByLabel("Payment reference").count()) await adminPage.getByLabel("Payment reference").fill(reference);
    await adminPage.getByLabel("Internal note", { exact:true }).fill("Browser internal note");
    await adminPage.getByRole("checkbox").setChecked(replace);
    const response = adminPage.waitForResponse(r => r.request().method()==="POST" && r.url().endsWith("/subscriptions"));
    await adminPage.getByRole("button", { name:"Activate Plan", exact:true }).click();
    if (replace) await adminPage.getByRole("button", {name:"Confirm action",exact:true}).click();
    assert.equal((await response).status(),201);
    await adminPage.getByText("Billing updated.", { exact:true }).waitFor();
  }
  await activate("desktop_starter","BROWSER-DESKTOP-001");
  await adminPage.getByRole("region",{name:"desktop",exact:true}).getByText("Desktop Starter",{exact:true}).waitFor();
  await activate("mobile_starter","BROWSER-MOBILE-001");
  await adminPage.getByRole("region",{name:"mobile",exact:true}).getByText("Mobile Starter",{exact:true}).waitFor();
  await adminPage.getByLabel("Extend desktop until").fill(new Date(Date.now()+120*86400000).toISOString().slice(0,16));
  const extended=adminPage.waitForResponse(r=>r.url().endsWith("/extend"));
  await adminPage.getByRole("button",{name:"Extend desktop",exact:true}).click();
  assert.equal((await extended).status(),200);
  await adminPage.getByText("Billing updated.",{exact:true}).waitFor();
  await activate("desktop_pro","BROWSER-UPGRADE",true);
  await adminPage.getByRole("region",{name:"desktop",exact:true}).getByText("Desktop Pro",{exact:true}).waitFor();
  await adminPage.getByRole("region",{name:"mobile",exact:true}).getByText("Mobile Starter",{exact:true}).waitFor();
  await adminPage.getByLabel("Checks to add or subtract").fill("500");
  await adminPage.getByLabel("Adjustment reason").fill("Browser goodwill");
  const adjusted=adminPage.waitForResponse(r=>r.url().endsWith("/usage-adjustments"));
  await adminPage.getByRole("button",{name:"Adjust usage",exact:true}).click();
  assert.equal((await adjusted).status(),200);
  await adminPage.getByText("Billing updated.",{exact:true}).waitFor();
  await adminPage.getByRole("region",{name:"desktop",exact:true}).getByText("50500",{exact:true}).waitFor();
  await adminPage.getByText(/Reference: BROWSER-DESKTOP-001/).waitFor();
  await adminPage.getByRole("heading",{name:"Billing audit",exact:true}).waitFor();
  await page.goto(`${base}/settings/billing`);
  await page.getByText("Desktop Pro",{exact:true}).waitFor();
  await page.getByText("Mobile Starter",{exact:true}).waitFor();
  assert(!(await page.locator("body").innerText()).includes("Browser internal note"));
  await verifyResponsive(adminPage,"admin-billing");
  await verifyResponsive(page,"billing-populated");
  await adminPage.goto(`${base}/admin/customers`);
  await adminPage.getByLabel("Search email").waitFor();
  await verifyResponsive(adminPage,"admin-customers");
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({billing_browser:"passed",customer:["signup","free_devices","project","project_keyword_limits","logical_check","separate_quotas","admin_denied"],admin:["login","customer_search","desktop_activation","mobile_activation","bank_reference","extension","upgrade","device_independence","history","usage_adjustment","audit"],browserExceptions:errors.length,realProviderCalls:0}));
} finally { await browser.close(); }
